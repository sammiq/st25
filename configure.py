#!/usr/bin/env python3
"""Generate build.ninja and objdiff.json from config/units.txt.

Re-run after adding a source file or changing units.txt (ninja also re-runs
it automatically when units.txt or this script changes).
"""

from __future__ import annotations

import json
import shlex
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
import ninja_syntax  # noqa: E402
from project import UNITS, exepack_tool, load_units  # noqa: E402

PY = shlex.quote(sys.executable)
OBJDIFF_CLI = "tools/bin/objdiff-cli"

# Microsoft C 6.00A flags. Medium model, 286 code; refine the optimization
# flags as functions start matching. Per-unit overrides go in UNIT_CFLAGS.
CFLAGS = ["/AM", "/G2", "/qc", "/Gs", "/Zp1", "/W3", "/ID:\\INCLUDE"]
UNIT_CFLAGS: dict[str, list[str]] = {
    # "seg000": ["/AM", "/G2", "/Os", "/Gs"],
    # CodeView info: QC then ends every line with an fwait after an FP store,
    # and the object pulls the runtime's debugger hooks (dbscrswp) into a link
    "seg006": CFLAGS + ["/Zi"],
}

TOOLS = ["tools/project.py", "tools/elf16.py", "config/aliases.txt"]


def check_original() -> None:
    """Verify the inputs listed in config/orig.sha1 (sha1sum format)."""
    import hashlib
    for line in (ROOT / "config/orig.sha1").read_text().splitlines():
        if not line.strip():
            continue
        digest, name = line.split(maxsplit=1)
        path = ROOT / name.lstrip("*")
        if not path.exists():
            sys.exit(f"configure: missing {name}; supply your own copy (see README)")
        if hashlib.sha1(path.read_bytes()).hexdigest() != digest:
            sys.exit(f"configure: {name} isn't the expected file (SHA-1 differs from config/orig.sha1)")


def main() -> None:
    check_original()
    units = load_units()
    n = ninja_syntax.Writer(open(ROOT / "build.ninja", "w"), width=120)
    n.comment("Generated by configure.py - do not edit")
    n.variable("python", PY)
    n.variable("exepack", shlex.quote(exepack_tool()))
    n.newline()

    n.rule("configure", f"$python configure.py", description="CONFIGURE", generator=True)
    n.rule("unpack", "$exepack -d $in $out", description="UNPACK $in")
    n.rule("split", f"$python tools/split.py && touch $out", description="SPLIT target objects")
    n.rule("cc", f"$python tools/cc.py $in $out --omf $omf -- $cflags", description="CC $in")
    n.rule("libobj", f"$python tools/omf2elf.py $in $out --module $module",
           description="LIB $module")
    n.rule("report", f"{OBJDIFF_CLI} report generate -p . -o $out -f json",
           description="REPORT")
    n.rule("progress", f"$python tools/progress.py $in", description="PROGRESS")
    n.newline()

    srcdirs = sorted({str(p.relative_to(ROOT)) for p in (ROOT / "src").rglob("*") if p.is_dir()}
                     | {"src"})
    n.build("build.ninja", "configure",
            implicit=["configure.py", str(UNITS.relative_to(ROOT)), *srcdirs])
    n.newline()

    # The original EXE is EXEPACK-compressed; the tools read its unpacked image
    n.build("build/exe/STARTREK.EXE", "unpack", "orig/CD/TREKCD/STARTREK.EXE")
    n.newline()

    targets = [f"build/target/{u.name}.o" for u in units]
    n.build("build/target/.stamp", "split",
            implicit=["build/exe/STARTREK.EXE", "config/ida_export.txt",
                      "config/symbols.txt", "config/units.txt", "config/relocs.txt", "tools/split.py", *TOOLS],
            implicit_outputs=targets)
    n.newline()

    headers = sorted(str(p.relative_to(ROOT)) for p in (ROOT / "include").rglob("*.h")) \
        if (ROOT / "include").exists() else []
    bases = []
    objdiff_units = []
    for u in units:
        meta = {"complete": "complete" in u.flags, "progress_categories": []}
        unit = {"name": u.name, "target_path": f"build/target/{u.name}.o"}
        base = f"build/base/{u.name}.o"
        lib = u.lib
        if lib:
            libfile, module = lib.split(":", 1)
            n.build(base, "libobj", f"tools/C600/LIB/{libfile}",
                    implicit=["tools/omf2elf.py", "tools/omf.py", *TOOLS],
                    variables={"module": module})
            unit["base_path"] = base
            meta["complete"] = True
            meta["progress_categories"] = ["lib"]
            bases.append(base)
        else:
            meta["progress_categories"] = ["data" if u.name.startswith(("data/", "far/")) else "game"]
            src = next((ROOT / "src" / f"{u.name}{ext}" for ext in (".c", ".asm")
                        if (ROOT / "src" / f"{u.name}{ext}").exists()), None)
            if src is not None:
                flags = UNIT_CFLAGS.get(u.name, CFLAGS) if src.suffix == ".c" else []
                rel = str(src.relative_to(ROOT))
                n.build(base, "cc", rel,
                        implicit=["tools/cc.py", "tools/omf2elf.py", "tools/omf.py", *TOOLS, *headers],
                        variables={"cflags": " ".join(flags), "omf": f"build/obj/{u.name}.obj"})
                unit["base_path"] = base
                meta["source_path"] = rel
                bases.append(base)
        unit["metadata"] = meta
        objdiff_units.append(unit)

    n.newline()
    n.build("base", "phony", bases)
    n.build("target", "phony", "build/target/.stamp")
    n.build("build/report.json", "report", ["build/target/.stamp", *bases, "objdiff.json"],
            implicit=[OBJDIFF_CLI])
    n.build("progress", "progress", "build/report.json")
    n.newline()

    # Room scripts: each src/rdf/<room>.asm must assemble to the room's .RDF
    n.rule("rdfcheck", "$python tools/rdf.py check $room --stamp $out", description="RDF $room")
    n.rule("rdfprogress", "$python tools/rdf.py progress", description="RDF PROGRESS")
    data = [f"orig/CD/TREKCD/DATA.{ext}" for ext in ("DIR", "RUN", "001")]
    stamps = []
    for src in sorted((ROOT / "src/rdf").glob("*.asm")):
        stamp = f"build/rdf/{src.stem}.ok"
        n.build(stamp, "rdfcheck", str(src.relative_to(ROOT)),
                implicit=["include/rdf.inc", "tools/rdf.py", "tools/resource.py", "tools/omf.py", *data],
                variables={"room": src.stem.upper()})
        stamps.append(stamp)
    n.build("rdf", "phony", stamps)
    n.build("rdf-progress", "rdfprogress", implicit=["config/rdf.txt", *stamps])
    n.default(["build/target/.stamp", "base", "rdf"])
    n.close()

    objdiff = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja",
        "custom_args": [],
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["*.c", "*.h", "*.asm", "*.inc", "*.txt"],
        "progress_categories": [
            {"id": "game", "name": "Game code"},
            {"id": "data", "name": "Game data"},
            {"id": "lib", "name": "C runtime"},
        ],
        "options": {"x86.formatter": "intel"},
        "units": objdiff_units,
    }
    (ROOT / "objdiff.json").write_text(json.dumps(objdiff, indent=2) + "\n")
    print(f"configured {len(units)} units ({len(bases)} with base objects)")


if __name__ == "__main__":
    main()
