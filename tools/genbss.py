#!/usr/bin/env python3
"""Write src/BSS.ASM: the original layout of the uninitialized globals.

    tools/genbss.py

The C sources define every uninitialized global (`int game_mode;`), which
MSC emits as a communal, and LINK lays communals out itself. Its order isn't
the definition order: it seems to follow LINK's symbol table, so it depends
on the original variable names, which are lost. For the full-EXE build
(STARTREK.MAK) to come out byte for byte, BSS.ASM defines each of them as a
public at its original address, sized to the next symbol so that unnamed
or unreferenced variables keep their space. LINK then resolves the C
files' communals to these publics instead of allocating them.

Both communal segments are covered: c_common in DGROUP (near globals) and
FAR_BSS (far arrays). BSS.ASM declares the segments LINK places before
them (the runtime's XOB/XO/XOE and the emulator's EMULATOR_DATA) so that the
segment order stays the original's. It has to be the last object linked.
It is a reproduction aid, not a recovered source file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from project import ROOT, SYMBOLS  # noqa: E402

OUT = ROOT / "src/BSS.ASM"
NEAR = (0x49F00, 0x53920)       # c_common: after XO, up to the stack
FAR = (0x44CE0, 0x45A46)        # FAR_BSS


def symbols_in(lo: int, hi: int) -> list[tuple[int, str]]:
    out = []
    for line in SYMBOLS.read_text().splitlines():
        f = line.split()
        if len(f) >= 4 and re.match(r"^[0-9A-F]{5}$", f[0]) and f[1] == "data":
            a = int(f[0], 16)
            if lo <= a < hi:
                out.append((a, f[3]))
    out.sort()
    if not out or out[0][0] != lo:
        sys.exit(f"genbss: no symbol at the start of {lo:05X}-{hi:05X}")
    return out


def body(lo: int, hi: int) -> list[str]:
    syms = symbols_in(lo, hi)
    lines = []
    for i, (a, name) in enumerate(syms):
        end = syms[i + 1][0] if i + 1 < len(syms) else hi
        lines += [f"\tPUBLIC\t{name}", f"{name}\tDB\t{end - a} DUP (?)\t; {a:05X}"]
    return lines


def main() -> None:
    out = ["; BSS.ASM - generated by tools/genbss.py from config/symbols.txt; do not edit.",
           "; The original layout of the uninitialized globals, for the full-EXE build",
           "; only (see the generator). Link it after every other object.",
           "",
           "_BSS\tSEGMENT WORD PUBLIC 'BSS'",
           "_BSS\tENDS",
           "XOB\tSEGMENT WORD PUBLIC 'BSS'",
           "XOB\tENDS",
           "XO\tSEGMENT WORD PUBLIC 'BSS'",
           "XO\tENDS",
           "XOE\tSEGMENT WORD PUBLIC 'BSS'",
           "XOE\tENDS",
           "c_common\tSEGMENT PARA PUBLIC 'BSS'",
           "c_common\tENDS",
           "",
           "; The C objects' references to these take their frame from the public,",
           "; so the publics must carry DGROUP: MASM records it under ASSUME DS:DGROUP.",
           "DGROUP\tGROUP\t_BSS, XOB, XO, XOE, c_common",
           "",
           "c_common\tSEGMENT",
           "\tASSUME\tDS:DGROUP",
           *body(*NEAR),
           "c_common\tENDS",
           "",
           "EMULATOR_DATA\tSEGMENT PARA PUBLIC 'FAR_DATA'",
           "EMULATOR_DATA\tENDS",
           "",
           "FAR_BSS\tSEGMENT PARA PUBLIC 'FAR_BSS'",
           "\tASSUME\tDS:NOTHING",
           *body(*FAR),
           "FAR_BSS\tENDS",
           "",
           "\tEND",
           ""]
    OUT.write_text("\r\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
